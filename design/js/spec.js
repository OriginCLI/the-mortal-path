// Turns the designer's answers into a Markdown spec (with embedded JSON) and a JSON spec.
import { TRIALS, realmFor } from './trials.js';
import { describeSlider } from './widgets.js';
import { hydrate, STATE_VERSION } from './state.js';

const sealedCount = (state) => TRIALS.filter((t) => state.sealed[t.id]).length;

function answerRecord(q, v) {
  switch (q.type) {
    case 'cards': {
      const byId = Object.fromEntries(q.options.map((o) => [o.id, o]));
      if (q.multi) return { value: v, labels: v.map((id) => byId[id].label) };
      return { value: v, label: byId[v].label, ...(byId[v].desc ? { description: byId[v].desc } : {}) };
    }
    case 'slider':
      return {
        value: v, label: describeSlider(q, v), min: q.min, max: q.max,
        scale: `${q.min} = ${q.left}, ${q.max} = ${q.right}`,
      };
    case 'rank': {
      const byId = Object.fromEntries(q.items.map((i) => [i.id, i.label]));
      return { value: v, labels: v.map((id) => byId[id]) };
    }
    default:
      return { value: v };
  }
}

export function buildJSON(state) {
  const n = sealedCount(state);
  const trials = {};
  for (const t of TRIALS) {
    const a = state.answers[t.id];
    const answers = {};
    for (const q of t.questions) answers[q.id] = { question: q.label, ...answerRecord(q, a[q.id]) };
    trials[t.id] = { topic: t.topic, title: t.title, sealed: !!state.sealed[t.id], answers, notes: a.notes || '' };
  }
  return {
    spec: 'the-mortal-path/design-spec',
    specVersion: STATE_VERSION,
    generatedAt: new Date().toISOString(),
    title: state.answers.scope.title || 'The Mortal Path',
    realmReached: realmFor(n).cur.en,
    trialsSealed: n,
    trialsTotal: TRIALS.length,
    trials,
    // Raw answers, so this file can be imported back into the Design Trials.
    answers: state.answers,
    sealed: state.sealed,
  };
}

const lbl = (t, qid) => t.questions.find((x) => x.id === qid);

function valueText(q, v) {
  const r = answerRecord(q, v);
  switch (q.type) {
    case 'cards':
      if (q.multi) return r.labels.length ? r.labels.join(', ') : '_none_';
      return r.description ? `${r.label}: ${r.description}` : r.label;
    case 'slider':
      return q.unit ? `${v} ${q.unit} _(range ${q.min}–${q.max}: ${q.left} → ${q.right})_`
        : `${v}/${q.max} · ${r.label} _(${q.min} = ${q.left}, ${q.max} = ${q.right})_`;
    case 'text':
      return v ? `“${v}”` : '_blank_';
    default:
      return String(v);
  }
}

function short(state, tid, qid) {
  const t = TRIALS.find((x) => x.id === tid);
  const q = lbl(t, qid);
  const v = state.answers[tid][qid];
  const r = answerRecord(q, v);
  if (q.type === 'slider') return q.unit ? `${v} ${q.unit}` : `${r.label} (${v})`;
  if (q.type === 'cards') return q.multi ? r.labels.join(', ') : r.label;
  if (q.type === 'rank') return r.labels.slice(0, 3).join(' > ');
  return String(v);
}

export function buildMarkdown(state) {
  const n = sealedCount(state);
  const realm = realmFor(n).cur;
  const title = state.answers.scope.title || 'The Mortal Path';
  const date = new Date().toISOString().slice(0, 10);
  const L = [];
  L.push(`# ${title}: Design Spec`, '');
  L.push(`> Generated by the Design Trials on ${date}. Realm reached: **${realm.en}** (${realm.ko} ${realm.hanja}), ${n}/${TRIALS.length} trials sealed.`);
  if (n < TRIALS.length) {
    const open = TRIALS.filter((t) => !state.sealed[t.id]).map((t) => t.topic).join(', ');
    L.push(`> Unsealed trials use their pre-filled defaults: ${open}.`);
  }
  L.push('', '## At a glance', '');
  const glance = [
    ['Voice & mood', `${short(state, 'tone', 'voice')}, ${short(state, 'tone', 'mood')}, ${short(state, 'tone', 'density')} prose, ${short(state, 'tone', 'terms')} terms`],
    ['World', `${short(state, 'setting', 'basis')}; factions: ${short(state, 'setting', 'factions')}`],
    ['Cultivation', `${short(state, 'cultivation', 'ladder')} (${short(state, 'cultivation', 'substages')}), pace ${short(state, 'cultivation', 'speed')}, risk ${short(state, 'cultivation', 'risk')}`],
    ['Combat', `${short(state, 'combat', 'system')}, ${short(state, 'combat', 'length')}, lethality ${short(state, 'combat', 'lethality')}`],
    ['Regression', `${short(state, 'regression', 'trigger')} → back to age ${state.answers.regression.returnAge}; carries ${short(state, 'regression', 'carry')}`],
    ['Bonds', `${short(state, 'relationships', 'romance')} romance; top bonds ${short(state, 'relationships', 'priorities')}`],
    ['Events', `${short(state, 'events', 'perYear')}, ${short(state, 'events', 'chains')} chaining; top ${short(state, 'events', 'categories')}`],
    ['Look', `${short(state, 'ui', 'palette')}, ${short(state, 'ui', 'layout')}, ${short(state, 'ui', 'type')}`],
    ['Sound', `${short(state, 'audio', 'music')} music in ${short(state, 'audio', 'scale')} at ${short(state, 'audio', 'tempo')}`],
    ['Difficulty', `${short(state, 'difficulty', 'overall')}, ${short(state, 'difficulty', 'failure')}`],
    ['First playable', `${short(state, 'scope', 'mustHave')}; ${short(state, 'scope', 'firstEvents')}`],
  ];
  for (const [k, v] of glance) L.push(`- **${k}:** ${v}`);

  TRIALS.forEach((t, i) => {
    const a = state.answers[t.id];
    L.push('', `## ${i + 1}. ${t.topic}: *${t.title}*`, '');
    L.push(`_${state.sealed[t.id] ? 'Sealed' : 'Not sealed (defaults)'}_`, '');
    for (const q of t.questions) {
      if (q.type === 'rank') {
        L.push(`- **${q.label}:**`);
        answerRecord(q, a[q.id]).labels.forEach((x, k) => L.push(`  ${k + 1}. ${x}`));
      } else {
        L.push(`- **${q.label}:** ${valueText(q, a[q.id])}`);
      }
    }
    if (a.notes && a.notes.trim()) {
      L.push('', '**Notes:**', '');
      a.notes.trim().split('\n').forEach((line) => L.push(`> ${line}`));
    }
  });

  L.push('', '## Machine-readable spec', '',
    'The same answers as JSON. Paste this block into the Design Trials import box to restore them.', '',
    '```json', JSON.stringify(buildJSON(state), null, 2), '```', '');
  return L.join('\n');
}

// Accepts a JSON spec, a raw answers export, or a Markdown spec with an embedded ```json block.
export function parseImport(text) {
  let src = text.trim();
  const m = src.match(/```json\s*([\s\S]*?)```/);
  if (m) src = m[1];
  const data = JSON.parse(src);
  if (!data || typeof data !== 'object' || !data.answers) throw new Error('No answers found in that file.');
  return hydrate(data);
}

export function rawExport(state) {
  return JSON.stringify({ spec: 'the-mortal-path/design-answers', specVersion: STATE_VERSION, answers: state.answers, sealed: state.sealed }, null, 2);
}
